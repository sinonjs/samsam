createMatcher.set.contains = function setContains(expectation) {
    return createMatcher(
        (actual) =>
            typeOf(actual) === "set" &&
            every(expectation, (element) => actual.has(element)),
        `contains(Set[${iterableToString(expectation)}])`,
    );
};

